def sn(mensagem):
    while True:
        try:
            voltar = input(f"\n{mensagem} (s/n): ").lower().strip()

            if voltar == "s":
                return True

            elif voltar == "n":
                print("\nPrograma encerrado.")
                return False

            print("Digite apenas s ou n.")

        except (KeyboardInterrupt, EOFError):
            print("\n\nPrograma encerrado.")
            return False

